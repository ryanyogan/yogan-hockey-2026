import { getGameSummary } from "@yogan-hockey/espn";
import { afterEach, describe, expect, test, vi } from "vitest";
import { predictionInputs, predictionRequest, readModelAnswer } from "./prediction";

const TEAMS: [string, string] = ["TOR", "NSH"];

const pick = {
  pick: "NSH",
  winProbability: 58,
  reasoning: "Nashville's goalie has the better numbers. Toronto is missing two centres.",
  keyFactors: ["Saros at .933", "Toronto's injuries"],
};

afterEach(() => {
  vi.unstubAllEnvs();
});

describe("reading a model's answer", () => {
  test("from a chat completion, the shape gpt-oss-120b answers in", () => {
    const raw = { choices: [{ message: { content: JSON.stringify(pick), reasoning: "..." } }] };
    expect(readModelAnswer(raw, TEAMS)).toEqual(pick);
  });

  test("from `response` already an object, as the llama model's JSON mode gives it", () => {
    const raw = { response: pick, choices: [{ message: { content: JSON.stringify(pick) } }] };
    expect(readModelAnswer(raw, TEAMS)).toEqual(pick);
  });

  test("from text with a code fence or a sentence around the JSON", () => {
    const text = `Here is the pick:\n\`\`\`json\n${JSON.stringify(pick, null, 2)}\n\`\`\``;
    expect(readModelAnswer({ response: text }, TEAMS)).toEqual(pick);
  });

  test.each([
    ["no answer at all", { choices: [{ message: { content: null } }] }],
    ["an answer cut off before the JSON closed", { response: '{"pick":"NSH","winProb' }],
    ["words and no JSON", { response: "Nashville, probably." }],
    ["JSON that is not a Prediction", { response: { pick: "NSH" } }],
    ["nothing", undefined],
  ])("%s is not a Prediction", (_name, raw) => {
    expect(readModelAnswer(raw, TEAMS)).toBeNull();
  });
});

describe("what the model is told about a game", () => {
  async function recordedInputs() {
    vi.stubEnv("ESPN_FIXTURES", "1");
    const { header, pregame } = await getGameSummary("401892449");
    return predictionInputs(header, pregame);
  }

  test("is each team's record, standing, last five, goalies, injuries and leaders, and the season series", async () => {
    const inputs = await recordedInputs();

    expect(inputs).toMatchObject({
      game: {
        start: "2026-10-06T23:00:00.000Z",
        venue: "Scotiabank Arena",
        kind: "regular season",
      },
      home: {
        team: "TOR",
        name: "Toronto Maple Leafs",
        record: { overall: "1-2-0", home: "1-2-0" },
        standing: { place: 7, division: "Atlantic Division", points: 2 },
      },
      away: { team: "NSH", record: { overall: "1-1-0", road: "0-0-0" } },
      seasonSeries: { summary: "Series starts 10/6", played: [] },
    });
    expect(inputs.home.lastFive).toHaveLength(5);
    expect(inputs.home.lastFive[4]).toEqual({
      date: "2026-10-03",
      where: "home",
      opponent: "OTT",
      result: "L 2-3",
    });
    expect(inputs.away.goalies).toEqual([
      {
        name: "Juuse Saros",
        gamesPlayed: 2,
        record: "1-1-0",
        goalsAgainstAverage: 2.03,
        savePct: 0.933,
      },
    ]);
    expect(inputs.away.injuries).toEqual([
      { name: "Justus Annunen", position: "G", status: "Injured Reserve", reason: "Undisclosed" },
    ]);
    expect(inputs.home.leaders).toContainEqual({
      stat: "goals",
      name: "William Nylander",
      value: 2,
    });
  });

  test("is sent as the user message, after instructions that name both teams and say it is for fun", async () => {
    const inputs = await recordedInputs();

    const { messages } = predictionRequest(inputs);

    expect(messages.map((message) => message.role)).toEqual(["system", "user"]);
    expect(JSON.parse(messages[1]?.content ?? "")).toEqual(inputs);
    expect(messages[0]?.content).toContain('exactly "TOR" or "NSH"');
    expect(messages[0]?.content).toContain("generated by AI, for fun");
  });

  test("is compact: a few kilobytes, not ESPN's summary", async () => {
    expect(JSON.stringify(await recordedInputs()).length).toBeLessThan(4000);
  });
});
