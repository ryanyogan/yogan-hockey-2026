import type { FinalGame, GameHeader, MadePrediction } from "@yogan-hockey/schemas";
import { pickOutcome } from "@yogan-hockey/schemas";
import { Badge } from "@yogan-hockey/ui/components/badge";
import { pickSentence } from "../../lib/agate-copy";
import { finalResult, pickedSide } from "../../lib/picks";
import { LocalTime } from "../local-time";
import { STORY_PICK } from "./game-story";

/**
 * The whole pick on a game page, the Reference UI's third tab: the story's pick line ("Our pick:
 * Toronto, 58%." in the serif's italic, `pickSentence`), the reasoning and the key factors in
 * agate, and when it was made with the line "generated by AI, for fun". The page's server component renders it once and
 * `GamePage` shows it as "The pick" section of a game still to come and as "the pick" tab after.
 *
 * `final` is the game's row in D1, there once the game is over and written: with it the pick is
 * marked Right (filled) or Wrong (outlined) on the pick line, with the score under it. Until then, a live game included, it is unmarked.
 *
 * Draws nothing for a pick whose team is not in the game.
 */
export function GamePick({
  prediction,
  header,
  final,
}: {
  prediction: MadePrediction;
  header: GameHeader;
  final: FinalGame | null;
}) {
  const side = pickedSide(prediction, header);
  if (side == null) return null;
  const outcome = pickOutcome(prediction, final);
  return (
    <div data-slot="game-pick-full" className="mt-3 max-w-prose space-y-3">
      <p data-slot="pick-lead" className={STORY_PICK}>
        {pickSentence(prediction, header)}
        {outcome != null && final != null && (
          <>
            {" "}
            <Badge
              data-slot="pick-outcome"
              data-outcome={outcome}
              variant={outcome === "right" ? "default" : "outline"}
              className="not-italic"
            >
              {outcome}
            </Badge>
          </>
        )}
      </p>
      {outcome != null && final != null && (
        <p data-slot="pick-result" className="text-aside text-small">
          {finalResult(final)}
        </p>
      )}
      <p data-slot="pick-reasoning" className="text-body">
        {prediction.reasoning}
      </p>
      {prediction.keyFactors.length > 0 && (
        <ul data-slot="pick-factors" className="text-note text-small">
          {prediction.keyFactors.map((factor) => (
            <li key={factor} className="flex gap-2">
              <span aria-hidden="true">-</span>
              {factor}
            </li>
          ))}
        </ul>
      )}
      <p data-slot="pick-made" className="text-label text-small">
        made <LocalTime at={prediction.madeAt} show="day" />,{" "}
        <LocalTime at={prediction.madeAt} show="time" /> · generated by AI, for fun
      </p>
    </div>
  );
}
